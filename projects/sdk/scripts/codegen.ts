import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import process from 'node:process'

const require = createRequire(import.meta.url)
const sdkDir = path.resolve(import.meta.dirname, '..')
const generatedDir = path.join(sdkDir, 'src', 'generated')
const localArtifactsDir = path.resolve(sdkDir, '../contracts/smart_contracts/artifacts')
const localContractsPackage = path.resolve(sdkDir, '../contracts/package.json')
const generatorBin = path.join(
  sdkDir,
  'node_modules',
  '.bin',
  process.platform === 'win32' ? 'algokit-client-generator.cmd' : 'algokit-client-generator',
)

function findSpecs(root: string): string[] {
  const specs: string[] = []
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const full = path.join(root, entry.name)
    if (entry.isDirectory()) specs.push(...findSpecs(full))
    else if (entry.name.endsWith('.arc56.json')) specs.push(full)
  }
  return specs.sort()
}

/**
 * Read the released contracts version from the package manifest.
 *
 * @param packageJsonPath The installed package.json path.
 * @returns The package version.
 */
function contractsVersionFromPackage(packageJsonPath: string): string {
  const version = (JSON.parse(fs.readFileSync(packageJsonPath, 'utf8')) as { version?: unknown }).version
  if (typeof version !== 'string' || version.length === 0) {
    throw new Error(`no version in ${packageJsonPath}`)
  }
  return version
}

function releaseContractsDir(): { specsDir: string; version: string } {
  let packageJsonPath: string
  try {
    packageJsonPath = require.resolve('@kasakame/contracts/package.json')
  } catch {
    throw new Error(
      'could not resolve @kasakame/contracts - install it (npm install --no-save @kasakame/contracts@<version>) or use SDK_SPECS=local',
    )
  }
  const packageDir = path.dirname(packageJsonPath)
  return {
    specsDir: path.join(packageDir, 'dist', 'arc56'),
    version: contractsVersionFromPackage(packageJsonPath),
  }
}

const source = process.env.SDK_SPECS ?? 'release'
if (source !== 'release' && source !== 'local') {
  throw new Error(`SDK_SPECS must be "release" or "local" (got: ${source})`)
}
if (!fs.existsSync(generatorBin)) {
  throw new Error(`algokit-client-generator is not installed at ${generatorBin} - run npm install`)
}

const contracts =
  source === 'local'
    ? {
        specsDir: localArtifactsDir,
        version: contractsVersionFromPackage(localContractsPackage),
      }
    : releaseContractsDir()

if (!fs.existsSync(contracts.specsDir)) {
  throw new Error(
    `no ARC-56 specs at ${contracts.specsDir} - build the contracts first (npm run build in projects/contracts) or install @kasakame/contracts`,
  )
}

const specs = findSpecs(contracts.specsDir)
if (specs.length === 0) throw new Error(`no *.arc56.json specs found under ${contracts.specsDir}`)

fs.rmSync(generatedDir, { recursive: true, force: true })
fs.mkdirSync(generatedDir, { recursive: true })
for (const spec of specs) {
  const name = path.basename(spec, '.arc56.json')
  const output = path.join(generatedDir, `${name}Client.ts`)
  execFileSync(generatorBin, ['generate', '--application', spec, '--output', output], { stdio: 'inherit' })
  // `exclude` doesn't remove imported files from the program, so the generated client opts out per file.
  fs.writeFileSync(output, `// @ts-nocheck\n${fs.readFileSync(output, 'utf8')}`)
  console.log(`generated ${path.relative(sdkDir, output)} from ${path.relative(contracts.specsDir, spec)}`)
}
fs.writeFileSync(
  path.join(generatedDir, 'specs-version.ts'),
  `// Generated by scripts/codegen.ts from the @kasakame/contracts version.\nexport const SPECS_VERSION = ${JSON.stringify(contracts.version)}\n`,
)
